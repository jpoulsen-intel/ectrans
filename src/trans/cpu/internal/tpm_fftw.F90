SUBROUTINE TPM_FFTW_FREE_MEMORY()
  IMPLICIT NONE

  IF (.NOT. LALLOPERM) THEN
     IF (JPRB == JPRD) THEN
        CALL FFTW_FREE(ZFFTWP)
     ELSE
