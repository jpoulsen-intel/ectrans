SUBROUTINE EC_FFTW_INIT_PLAN(KDLON)
  USE TPM_DIM,      ONLY : R
  USE TPM_GEOMETRY, ONLY : G
  IMPLICIT NONE
  INTEGER(KIND=JPIM),OPTIONAL, INTENT(IN) :: KDLON

  INTEGER(KIND=JPIM) :: I, FAKEKN

  IF (.NOT.G%LREDUCED_GRID) THEN
    IF (PRESENT(KDLON)) THEN
      ALLOCATE(FFTW_DIR_R1(KDLON))
      FFTW_DIR_R1(:)=123456
      ALLOCATE(FFTW_INV_R1(KDLON))
      FFTW_INV_R1(:)=123456
    ENDIF
    STOP 'NOT TESTED YET, ONLY TESTED FOR FOR REDUCED GRIDS'
    ! FIXME create plans for regular GAUSSIAN grid here
  ELSE
    ! NOTE - assumes that R%NSMAX is properly set per resolution, i.e. that
    ! we can rely on R%NSMAX also in DA context where resolution is being changed
    ! during the same incarnation
    ALLOCATE(FFTW_DIR_R1(R%NSMAX+1))
    FFTW_DIR_R1(:)=123456
    ALLOCATE(FFTW_INV_R1(R%NSMAX+1))
    FFTW_INV_R1(:)=123456
    DO I = (R%NSMAX+1), 1, -1 
      ! avoid re-allocations by taking the largest first
      FAKEKN = 20 + 4 * (i - 1)
      CALL CREATE_PLAN_FFTW_DIR_R1(FAKEKN)
      CALL CREATE_PLAN_FFTW_INV_R1(FAKEKN)
    ENDDO
  ENDIF
END SUBROUTINE EC_FFTW_INIT_PLAN

SUBROUTINE CREATE_PLAN_FFTW_INV_R1(KN)
USE TPM_GEOMETRY, ONLY : G
#if defined (_OPENMP)
    USE OMP_LIB,   only : OMP_IN_PARALLEL
#endif
INTEGER(KIND=JPIM),INTENT(IN)        :: KN
INTEGER(KIND=JPIB)                   :: IPLAN
INTEGER(KIND=JPIM)                   :: KNIDX
REAL(KIND=JPHOOK)                    :: ZHOOK_HANDLE, ZHOOK_HANDLE2
REAL(KIND=JPRB), POINTER, CONTIGUOUS :: ZDUM(:)

IF (LHOOK) CALL DR_HOOK('CREATE_PLAN_FFTW_INV_R1',0,ZHOOK_HANDLE)

#if defined (_OPENMP)
IF (OMP_IN_PARALLEL()) THEN
  CALL ABOR1('CREATE_PLAN_FFTW_INV_R1: CANNOT BE CALLED IN OMP PARALLEL CONTEXT')
ENDIF
#endif

IF (.NOT.G%LREDUCED_GRID) THEN
  KNIDX=KN ! maintaining the original strategy for regular Gaussion
ELSE
  KNIDX=(((KN-20)/4) + 1) ! compute index for plans to allow for reduced footprint
ENDIF

IF( KNIDX > SIZE(FFTW_INV_R1) )THEN
  CALL ABOR1('CREATE_PLAN_FFTW_INV_R1: KNIDX > N_MAX THAT WAS INITIALISED IN INIT_PLANS_FFTW')
ENDIF

IF (FFTW_INV_R1(KNIDX) == 123456 )THEN
   CALL TPM_FFTW_ALLOCATE_MEMORY_R1(KN, ZDUM)
   IF (LHOOK) CALL DR_HOOK('FFTW_PLAN_DFT_C2R_1D',0,ZHOOK_HANDLE2)
   IF (JPRB == JPRD) THEN
      CALL DFFTW_PLAN_DFT_C2R_1D(IPLAN,KN,ZDUM,ZDUM,FFTW_ESTIMATE+FFTW_UNALIGNED)
   ELSE
      CALL SFFTW_PLAN_DFT_C2R_1D(IPLAN,KN,ZDUM,ZDUM,FFTW_ESTIMATE+FFTW_UNALIGNED)
      ! Note that MKL allow FFTW_MEASURE, but libfftw3 does not when doing it in-place
      ! Work-around for FFTW_MEASURE with libfftw3 is to add the +FFTW_UNALIGNED coming from KOFF:
   ENDIF
   IF (LHOOK) CALL DR_HOOK('FFTW_PLAN_DFT_C2R_1D',1,ZHOOK_HANDLE2)
   FFTW_INV_R1(KNIDX)=IPLAN
ELSE
  CALL ABOR1('CREATE_PLAN_FFTW_INV_R1 HAS RECEIVED TWO CALLS TO CREATE SAME PLAN')
ENDIF
IF (LHOOK) CALL DR_HOOK('CREATE_PLAN_FFTW_INV_R1',1,ZHOOK_HANDLE)
END SUBROUTINE CREATE_PLAN_FFTW_INV_R1

