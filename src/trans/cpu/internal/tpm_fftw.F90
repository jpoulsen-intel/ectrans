SUBROUTINE TPM_FFTW_ALLOCATE_MEMORY_R1(KCLEN, ZFFT)
  IMPLICIT NONE

  INTEGER(KIND=JPIM),INTENT(IN)   :: KCLEN
  REAL(KIND=JPRB), POINTER, CONTIGUOUS :: ZFFT(:)
  
  INTEGER(KIND=C_SIZE_T) :: NMEM_PLAN_FFTW
  
  ! Only really allocate memory if needed
  NMEM_PLAN_FFTW=INT(KCLEN/2,C_SIZE_T)
  IF (ZFFTWP_SIZE < NMEM_PLAN_FFTW) THEN
    CALL ALLOCATE_MEMORY_FFTW(ZFFTWP, NMEM_PLAN_FFTW)
    ZFFTWP_SIZE = NMEM_PLAN_FFTW
  END IF
  ! ZFFTP is large enough to fit KCLEN*KFIELDS
  CALL C_F_POINTER(ZFFTWP,ZFFT,[KCLEN])
END SUBROUTINE TPM_FFTW_ALLOCATE_MEMORY_R1

SUBROUTINE TPM_FFTW_ALLOCATE_MEMORY_R2(KCLEN, KFIELDS, ZFFT)
  IMPLICIT NONE

  INTEGER(KIND=JPIM),INTENT(IN)   :: KCLEN
  INTEGER(KIND=JPIM),INTENT(IN)   :: KFIELDS
  REAL(KIND=JPRB), POINTER, CONTIGUOUS :: ZFFT(:,:)
  
  INTEGER(KIND=C_SIZE_T) :: NMEM_PLAN_FFTW
  
  ! Only really allocate memory if needed
  NMEM_PLAN_FFTW=INT(KCLEN/2*KFIELDS,C_SIZE_T)
  IF (ZFFTWP_SIZE < NMEM_PLAN_FFTW) THEN
    CALL ALLOCATE_MEMORY_FFTW(ZFFTWP, NMEM_PLAN_FFTW)
    ZFFTWP_SIZE = NMEM_PLAN_FFTW
  END IF
  ! ZFFTP is large enough to fit KCLEN*KFIELDS
  CALL C_F_POINTER(ZFFTWP,ZFFT,[KCLEN,KFIELDS])
END SUBROUTINE TPM_FFTW_ALLOCATE_MEMORY_R2

SUBROUTINE TPM_FFTW_DFT_INV_R1(KRLEN,KCLEN,KOFF,PREEL,PFFT,JF)
  IMPLICIT NONE

  INTEGER(KIND=JPIM),INTENT(IN)   :: KRLEN
  INTEGER(KIND=JPIM),INTENT(IN)   :: KCLEN
  INTEGER(KIND=JPIM),INTENT(IN)   :: KOFF
  INTEGER(KIND=JPIM),INTENT(IN)   :: JF
  REAL(KIND=JPRB), CONTIGUOUS, INTENT(INOUT)  :: PREEL(:,:)
  REAL(KIND=JPRB) :: PFFT(KCLEN)

  INTEGER(KIND=JPIB) :: IPLAN_INV
  INTEGER(KIND=JPIM) :: JJ

  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

  CALL TPM_FFTW_GET_PLAN_INV(IPLAN_INV,KRLEN)
  !DIR$ IVDEP
  DO JJ=1,KCLEN
     PFFT(JJ) =PREEL(JF,KOFF+JJ-1) ! FIXME this is a step, we need transpose of PREEL
  ENDDO

  IF (LHOOK) CALL DR_HOOK('FFTW_EXECUTE_DFT_C2R',0,ZHOOK_HANDLE)
  CALL TPM_FFTW_EXECUTE_DFT_INV(IPLAN_INV,PFFT)
  IF (LHOOK) CALL DR_HOOK('FFTW_EXECUTE_DFT_C2R',1,ZHOOK_HANDLE)

  DO JJ=1,KRLEN
     PREEL(JF,KOFF+JJ-1)=PFFT(JJ) ! FIXME this is a step, we need transpose of PREEL
  ENDDO
END SUBROUTINE TPM_FFTW_DFT_INV_R1

SUBROUTINE TPM_FFTW_DFT_INV_R1_INPLACE(KRLEN,KCLEN,KOFF,PREEL)
  IMPLICIT NONE

  INTEGER(KIND=JPIM),INTENT(IN)   :: KRLEN
  INTEGER(KIND=JPIM),INTENT(IN)   :: KCLEN
  INTEGER(KIND=JPIM),INTENT(IN)   :: KOFF
  REAL(KIND=JPRB), CONTIGUOUS, INTENT(INOUT)  :: PREEL(:)

  INTEGER(KIND=JPIB) :: IPLAN_INV

