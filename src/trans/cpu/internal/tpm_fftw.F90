SUBROUTINE ALLOCATE_MEMORY_FFTW( FFTWMEM_PTR, NMEM )
  TYPE(C_PTR) :: FFTWMEM_PTR
  INTEGER(C_SIZE_T) :: NMEM
  CALL DEALLOCATE_MEMORY_FFTW( FFTWMEM_PTR )
  IF (JPRB == JPRD) THEN
    FFTWMEM_PTR=FFTW_ALLOC_COMPLEX(NMEM)
  ELSE
    FFTWMEM_PTR=FFTWF_ALLOC_COMPLEX(NMEM)
  END IF
END SUBROUTINE ALLOCATE_MEMORY_FFTW

SUBROUTINE DEALLOCATE_MEMORY_FFTW( FFTWMEM_PTR )
  TYPE(C_PTR) :: FFTWMEM_PTR
  IF( C_ASSOCIATED(FFTWMEM_PTR) ) THEN
    IF (JPRB == JPRD) THEN
      CALL FFTW_FREE(FFTWMEM_PTR)
    ELSE
      CALL FFTWF_FREE(FFTWMEM_PTR)
    END IF
  END IF
END SUBROUTINE DEALLOCATE_MEMORY_FFTW

